<!-- Script for Curated Offers slider movement and Hero Promo slider -->
<script>
    const track = document.getElementById('curated-slider');
    const prevBtn = document.getElementById('curated-prev');
    const nextBtn = document.getElementById('curated-right');
    const dots = document.querySelectorAll('.curated-dot');
    let currentIndex = 0;
    
    function getSlideWidth() {
      const container = document.getElementById('curated-slider-container');
      if (!container) return 0;
      const containerWidth = container.offsetWidth;
      if (window.innerWidth >= 1024) {
        return (containerWidth - 48) / 3; // 3 slides on large
      } else if (window.innerWidth >= 768) {
        return (containerWidth - 24) / 2; // 2 slides on tablet
      } else {
        return containerWidth; // 1 slide on mobile
      }
    }

    function getMaxIndex() {
      if (!track) return 0;
      const totalSlides = track.children.length;
      if (window.innerWidth >= 1024) {
        return Math.max(0, totalSlides - 3);
      } else if (window.innerWidth >= 768) {
        return Math.max(0, totalSlides - 2);
      } else {
        return Math.max(0, totalSlides - 1);
      }
    }

    function updateSlider() {
      if (!track) return;
      const slideWidth = getSlideWidth();
      const gap = 24; // flex gap-6 is 24px
      const shift = currentIndex * (slideWidth + gap);
      
      track.style.transform = `translateX(-${shift}px)`;
      
      // Update dots highlights
      const maxIndex = getMaxIndex();
      const dotCount = dots.length;
      dots.forEach((dot, idx) => {
        const segment = Math.ceil(maxIndex / dotCount);
        const activeDot = Math.min(Math.floor(currentIndex / (segment || 1)), dotCount - 1);
        if (idx === activeDot) {
          dot.classList.add('bg-accentYellow');
          dot.classList.remove('bg-slate-500');
          dot.style.opacity = '1';
        } else {
          dot.classList.add('bg-slate-500');
          dot.classList.remove('bg-accentYellow');
          dot.style.opacity = '0.5';
        }
      });
    }

    // Auto-scroll functionality
    let autoScrollInterval;
    function startAutoScroll() {
      autoScrollInterval = setInterval(() => {
        const maxIndex = getMaxIndex();
        if (currentIndex < maxIndex) {
          currentIndex++;
        } else {
          currentIndex = 0;
        }
        updateSlider();
      }, 5000); // changes slides every 5 seconds
    }

    function stopAutoScroll() {
      clearInterval(autoScrollInterval);
    }

    if (track) {
      startAutoScroll();

      // Pause on hover
      const sliderContainer = document.getElementById('curated-slider-container');
      if (sliderContainer) {
        sliderContainer.addEventListener('mouseenter', stopAutoScroll);
        sliderContainer.addEventListener('mouseleave', startAutoScroll);
      }

      if (nextBtn) {
        nextBtn.addEventListener('click', () => {
          stopAutoScroll();
          const maxIndex = getMaxIndex();
          if (currentIndex < maxIndex) {
            currentIndex++;
          } else {
            currentIndex = 0; // loop back
          }
          updateSlider();
          startAutoScroll();
        });
      }

      if (prevBtn) {
        prevBtn.addEventListener('click', () => {
          stopAutoScroll();
          const maxIndex = getMaxIndex();
          if (currentIndex > 0) {
            currentIndex--;
          } else {
            currentIndex = maxIndex; // loop to end
          }
          updateSlider();
          startAutoScroll();
        });
      }

      // Touch swipe support on mobile devices
      let touchStartX = 0;
      let touchEndX = 0;
      
      track.addEventListener('touchstart', (e) => {
        touchStartX = e.changedTouches[0].screenX;
      }, { passive: true });

      track.addEventListener('touchend', (e) => {
        touchEndX = e.changedTouches[0].screenX;
        handleSwipe();
      }, { passive: true });

      function handleSwipe() {
        const swipeThreshold = 50;
        const maxIndex = getMaxIndex();
        if (touchStartX - touchEndX > swipeThreshold) {
          stopAutoScroll();
          if (currentIndex < maxIndex) {
            currentIndex++;
          } else {
            currentIndex = 0;
          }
          updateSlider();
          startAutoScroll();
        } else if (touchEndX - touchStartX > swipeThreshold) {
          stopAutoScroll();
          if (currentIndex > 0) {
            currentIndex--;
          } else {
            currentIndex = maxIndex;
          }
          updateSlider();
          startAutoScroll();
        }
      }

      // Sync resize
      window.addEventListener('resize', () => {
        currentIndex = 0;
        updateSlider();
      });

      // Sync dot clicks
      dots.forEach((dot, idx) => {
        dot.addEventListener('click', () => {
          stopAutoScroll();
          const maxIndex = getMaxIndex();
          currentIndex = Math.min(idx, maxIndex);
          updateSlider();
          startAutoScroll();
        });
      });

      updateSlider();
    }

    // Auto rotation for Hero Promo slider (rotates every 4 seconds)
    const heroSlides = document.querySelectorAll('.hero-slide');
    if (heroSlides.length > 0) {
      let currentHeroIndex = 0;
      setInterval(() => {
        // Fade out current slide
        const prevSlide = heroSlides[currentHeroIndex];
        if (prevSlide) {
          prevSlide.classList.remove('opacity-100');
          prevSlide.classList.add('opacity-0', 'pointer-events-none');
        }
        
        // Move to next slide index
        currentHeroIndex = (currentHeroIndex + 1) % heroSlides.length;
        
        // Fade in next slide
        const nextSlide = heroSlides[currentHeroIndex];
        if (nextSlide) {
          nextSlide.classList.remove('opacity-0', 'pointer-events-none');
          nextSlide.classList.add('opacity-100');
        }
      }, 4000);
    }
</script>

